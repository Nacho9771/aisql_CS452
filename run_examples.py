"""Run real experiments and write an evidence file; reference SQL is never sent to GPT."""
import argparse
from collections import Counter
from datetime import datetime
from decimal import Decimal
import json
from pathlib import Path
from db_bot import (DEFAULT_MODEL, ROOT, GymBot, GymDatabase, SQLiteGymDatabase,
                    OpenAIClient, json_value, save_record)
from prompting import STRATEGIES


def normalized_rows(result):
    def cell(value):
        if isinstance(value, (int, float, Decimal)):
            return format(Decimal(str(value)).quantize(Decimal('0.000001')), 'f')
        return str(value) if value is not None else '<NULL>'
    return Counter(tuple(cell(v) for v in row) for row in result['rows'])


def markdown_report(records, questions):
    lines = ['# Gym SQL: real experiment results', '',
             'Generated by run_examples.py from actual OpenAI calls and database queries.',
             'Reference SQL was evaluated locally and was not included in model prompts.',
             'A result match compares row values/multiplicity, ignoring aliases and row order.',
             'Different column ordering or formatting can require manual review; matches on',
             'this finite fictional dataset do not prove correctness on every database.', '',
             '| Strategy | Reference result/status matches | Runs | Estimated API cost |',
             '| --- | ---: | ---: | ---: |']
    for strategy in sorted({r['strategy'] for r in records}):
        selected = [r for r in records if r['strategy'] == strategy]
        successes = sum(r.get('reference_match') is True for r in selected)
        cost = sum(r.get('estimated_cost_usd') or 0 for r in selected)
        lines.append(f'| {strategy} | {successes} | {len(selected)} | ${cost:.6f} |')
    for record in records:
        lines.extend(['', f'## {record["question_id"]} — {record["strategy"]}', '',
                      '**Question:** ' + record['question'], '',
                      '**Status:** ' + record['status'],
                      '**Reference match:** ' + str(record.get('reference_match')), '',
                      '**Generated SQL:**', '```sql', record.get('generated_sql') or '(No SQL generated)', '```',
                      '**Executed SQL:**', '```sql', record.get('executed_sql') or '(No SQL executed)', '```',
                      '**Database result:**', '```json', json.dumps(record.get('result'), indent=2, default=json_value),
                      '```', '**Plain-language response:** ' + record['answer'], '',
                      '**Expected/reference result:**', '```json',
                      json.dumps(record.get('reference_result'), indent=2, default=json_value), '```',
                      '**Token usage:** ' + json.dumps(record['usage']),
                      '**Estimated cost (USD):** ' + str(record.get('estimated_cost_usd')),
                      '**Run time:** ' + record['run_at']])
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=ROOT / 'config.json')
    parser.add_argument('--database', type=Path, default=ROOT / 'gym.db')
    parser.add_argument('--db-config', type=Path, default=ROOT / 'db_config.json')
    parser.add_argument('--engine', choices=('sqlite', 'mysql'), default='sqlite')
    parser.add_argument('--model', default=DEFAULT_MODEL)
    parser.add_argument('--strategies', nargs='+', choices=STRATEGIES, default=list(STRATEGIES))
    parser.add_argument('--questions', type=Path, default=ROOT / 'experiment_questions.json')
    parser.add_argument('--ids', nargs='+', help='Run only selected question IDs.')
    parser.add_argument('--today', default='2026-10-12')
    parser.add_argument('--output', type=Path, default=ROOT / 'examples.md')
    args = parser.parse_args()
    questions = json.loads(args.questions.read_text(encoding='utf-8'))
    if args.ids:
        questions = [q for q in questions if q['id'] in args.ids]
    if not questions:
        raise SystemExit('No questions selected.')
    if args.engine != 'sqlite':
        raise SystemExit('The supplied reference queries use SQLite. Adapt reference SQL before running MySQL experiments.')
    db = SQLiteGymDatabase(args.database)
    records = []
    try:
        bot = GymBot(db, OpenAIClient(args.config, args.model), args.today)
        for question in questions:
            reference = db.query(question['reference_sql'])[1] if question['reference_sql'] else None
            for strategy in args.strategies:
                print(f'Running {question["id"]}: {strategy}', flush=True)
                record = bot.ask(question['question'], strategy)
                record.update(question_id=question['id'], question_origin=question['origin'],
                              reference_result=reference)
                if reference is None:
                    record['reference_match'] = record['status'] == question['expected_status']
                else:
                    record['reference_match'] = (
                        record['status'] == 'answered'
                        and normalized_rows(record['result']) == normalized_rows(reference))
                records.append(record)
                save_record(record)
                # Persist after each run so interrupted or failed experiments retain their evidence.
                args.output.write_text(markdown_report(records, questions), encoding='utf-8')
                args.output.with_suffix('.json').write_text(json.dumps(records, indent=2, default=json_value), encoding='utf-8')
                print(f'  {record["status"]}; reference match={record["reference_match"]}; estimated cost={record["estimated_cost_usd"]}', flush=True)
                if record['status'] == 'error' and record['answer'].startswith('OpenAI '):
                    raise SystemExit('Stopped after an API error; results so far were saved.')
        print(f'Saved {len(records)} real runs to {args.output.name}')
    finally:
        db.close()


if __name__ == '__main__':
    main()
